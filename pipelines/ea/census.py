import json
import re
from datetime import date
from pathlib import Path

from ea.store import ROOT, connect

PAGES = ROOT / ".agents" / "spec" / "coverage"
RESEARCH = "## Research"
TICKET_REF = re.compile(r"class:([a-z]{2,3})/([a-z0-9_.-]+)")

CLASSES_SQL = """
select k.id, k.key, k.name_en, k.name, k.category, k.goal, k.valid_from, k.valid_to, k.first_held, k.earliest_record,
    k.contests_per_unit, k.finest_scheme_code, k.finest_note, k.disposition, k.disposition_reason, k.est_votes,
    k.effort, k.note, t.key as tier_key,
    (select count(*) from contest_class cc join contest c on c.id = cc.contest_id where cc.class_id = k.id and not c.notional) as held,
    (select sum(g.complete)::float / nullif(sum(g.total), 0) from coverage_goal g where g.class_id = k.id) as share,
    (select min(d.date) from census_date d where d.class_id = k.id and d.date >= %(today)s) as next_date
from census_class k
join census_tier t on t.id = k.tier_id
where k.polity_id = %(polity)s
order by t.key, k.key
"""


def polity_id(conn, cc: str) -> str:
    row = conn.execute("select id from polity where iso_code = %s", (cc.upper(),)).fetchone()
    if row is None:
        raise SystemExit(f"no polity {cc.upper()}")
    return row[0]


def open_classes(conn) -> list[dict]:
    rows = conn.execute(
        """
        select lower(p.iso_code), k.key, coalesce(k.name_en, k.name), t.key, k.est_votes, k.effort
        from census_class k
        join census_tier t on t.id = k.tier_id
        join polity p on p.id = k.polity_id
        where k.disposition is null
            and not exists (
                select 1 from contest_class cc join contest c on c.id = cc.contest_id
                where cc.class_id = k.id and not c.notional)
        """
    ).fetchall()
    found = [
        {
            "polity": cc,
            "key": key,
            "name": name,
            "tier": tier,
            "est_votes": votes,
            "effort": effort,
            "score": (votes or 0) / (effort or 3),
        }
        for cc, key, name, tier, votes, effort in rows
    ]
    found.sort(key=lambda row: (-row["score"], row["polity"], row["key"]))
    return found


def status_of(row: dict, queued: set[tuple[str, str]], cc: str) -> str:
    if row["held"]:
        return "held"
    if row["disposition"]:
        return row["disposition"].replace("_", " ")
    return "queued" if (cc, row["key"]) in queued else "open"


def span(first, last) -> str:
    if first is None and last is None:
        return ""
    return f"{first.year if first else ''}-{last.year if last else ''}"


def cell(text) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ")


def table(head: list[str], rows: list[list]) -> list[str]:
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(cell(value) for value in row) + " |" for row in rows]
    return lines + [""]


def render(conn, cc: str, queued: set[tuple[str, str]]) -> str:
    pid = polity_id(conn, cc)
    name = conn.execute(
        "select coalesce((select text from name where entity_id = %s and is_preferred limit 1), %s)", (pid, cc.upper())
    ).fetchone()[0]
    out = [
        f"# {name} election census",
        "",
        "Generated by `ea census " + cc.lower() + "` from the database; edit the research below the marker only.",
        "",
    ]

    tiers = conn.execute(
        """
        select t.id, t.key, coalesce(t.name_en, t.name), t.parent_tier_id, t.elects, t.valid_from, t.valid_to,
            t.polity_kind, t.scheme_code, w.iso_code, t.locator, s.publisher, s.url
        from census_tier t
        join source s on s.id = t.source_id
        left join polity w on w.id = t.within_polity_id
        where t.polity_id = %s
        """,
        (pid,),
    ).fetchall()
    counts = {
        tier_id: (when, value, locator, publisher)
        for tier_id, when, value, locator, publisher in conn.execute(
            """
            select distinct on (c.tier_id) c.tier_id, c.date, sum(c.value) over (partition by c.tier_id, c.date),
                c.locator, s.publisher
            from census_tier_count c
            join census_tier t on t.id = c.tier_id and t.polity_id = %s
            join source s on s.id = c.source_id
            order by c.tier_id, c.date desc
            """,
            (pid,),
        )
    }
    keys = {tier[0]: tier[1] for tier in tiers}
    out += ["## Tiers", ""]
    rows = []
    for tier_id, key, label, parent, elects, vfrom, vto, kind, scheme, within, locator, publisher, _ in sorted(
        tiers, key=lambda t: t[1]
    ):
        count = counts.get(tier_id)
        rows.append(
            [
                key,
                label,
                keys.get(parent, ""),
                "yes" if elects else "no",
                kind or "",
                scheme or "",
                within or "",
                span(vfrom, vto),
                f"{count[1]:,} on {count[0]} ({count[3]}, {count[2]})" if count else "",
            ]
        )
    out += (
        table(["Key", "Tier", "Parent", "Elects", "Polity kind", "Scheme", "Within", "Years", "Units"], rows)
        if rows
        else ["None recorded.", ""]
    )

    classes = [
        dict(zip([c.name for c in cur.description], record, strict=True))
        for cur in [conn.execute(CLASSES_SQL, {"polity": pid, "today": date.today()})]
        for record in cur.fetchall()
    ]
    cadence: dict = {}
    for (
        class_id,
        period,
        phase,
        month,
        day_rule,
        called,
        term,
        system,
        administered,
        statute,
        vfrom,
        vto,
    ) in conn.execute(
        """
        select c.class_id, c.period_years, c.phase, c.month, c.day_rule, c.called, c.term_years, (select n.text from name n where n.entity_id = c.electoral_system_id and n.is_preferred limit 1),
            c.administered_by, c.locator, c.valid_from, c.valid_to
        from election_cadence c
        where c.class_id in (select id from census_class where polity_id = %s)
        order by c.valid_from nulls first
        """,
        (pid,),
    ):
        text = f"every {period} y" if period else "irregular"
        text += f", month {month}" if month else ""
        text += f", {day_rule}" if day_rule else ""
        text += ", can be called early" if called else ""
        text += f", {system}" if system else ""
        text += f" ({statute}{', ' + span(vfrom, vto) if vfrom or vto else ''})"
        cadence.setdefault(class_id, []).append(text)
    access: dict = {}
    for class_id, role, platform, url, fmt, level, license_ in conn.execute(
        """
        select a.class_id, a.role, a.platform, a.url_pattern, a.format, a.access, a.license
        from results_access a
        where a.class_id in (select id from census_class where polity_id = %s)
        order by a.role, a.platform
        """,
        (pid,),
    ):
        access.setdefault(class_id, []).append(
            f"{role}: {platform} {url} ({fmt}, {level}{', ' + license_ if license_ else ''})"
        )

    tier_order = sorted({k["tier_key"] for k in classes})
    live = [k for k in classes if k["valid_to"] is None or k["valid_to"] >= date.today()]
    closed = [k for k in classes if k not in live]
    out += ["## Classes", ""]
    for tier in tier_order:
        out += [f"### {tier}", ""]
        rows = []
        for k in (k for k in live if k["tier_key"] == tier):
            share = k["share"]
            rows.append(
                [
                    k["key"],
                    k["name_en"] or k["name"],
                    k["category"],
                    span(k["valid_from"], k["valid_to"]),
                    "; ".join(cadence.get(k["id"], [])),
                    "; ".join(access.get(k["id"], [])),
                    (k["finest_scheme_code"] or "") + (f" ({k['finest_note']})" if k["finest_note"] else ""),
                    status_of(k, queued, cc.lower()) + (f": {k['disposition_reason']}" if k["disposition"] else ""),
                    f"{share:.0%}" if share is not None else "0%" if not k["disposition"] else "",
                    k["next_date"] or "",
                ]
            )
        out += table(
            [
                "Class",
                "Name",
                "Category",
                "Years",
                "Cadence",
                "Publishers",
                "Finest unit",
                "Status",
                "Coverage",
                "Next",
            ],
            rows,
        )
    if not classes:
        out += ["None recorded.", ""]
    if closed:
        out += ["## Abolished classes", ""]
        out += table(
            ["Class", "Name", "Years", "Status"],
            [
                [
                    k["key"],
                    k["name_en"] or k["name"],
                    span(k["valid_from"], k["valid_to"]),
                    status_of(k, queued, cc.lower()),
                ]
                for k in closed
            ],
        )
    ranked = sorted(
        (k for k in live if status_of(k, queued, cc.lower()) in ("open", "queued")),
        key=lambda k: -((k["est_votes"] or 0) / (k["effort"] or 3)),
    )
    out += ["## Open classes", ""]
    out += (
        table(
            ["Class", "Status", "Est. votes", "Effort"],
            [
                [
                    k["key"],
                    status_of(k, queued, cc.lower()),
                    f"{k['est_votes']:,}" if k["est_votes"] else "",
                    k["effort"] or "",
                ]
                for k in ranked
            ],
        )
        if ranked
        else ["None.", ""]
    )
    return "\n".join(out)


def page(conn, cc: str, queued: set[tuple[str, str]] | None = None) -> Path:
    path = PAGES / f"{cc.lower()}-census.md"
    kept = ""
    if path.exists():
        text = path.read_text()
        at = text.find("\n" + RESEARCH)
        if at >= 0:
            kept = text[at + 1 :]
        elif text.startswith(RESEARCH):
            kept = text
    body = render(conn, cc, queued or set())
    path.write_text(body.rstrip("\n") + "\n\n" + (kept.rstrip("\n") if kept else RESEARCH + "\n\n") + "\n")
    return path


def queued_classes(text: str) -> set[tuple[str, str]]:
    return set(TICKET_REF.findall(text))


def run(targets: list[str], as_json: bool, queued_file: str | None) -> str:
    with connect() as conn:
        if targets == ["open"]:
            found = open_classes(conn)
            if as_json:
                return json.dumps(found, indent=2)
            return "\n".join(f"{r['polity']}/{r['key']}\t{r['score']:.0f}\t{r['name']}" for r in found)
        queued = queued_classes(Path(queued_file).read_text()) if queued_file else set()
        return "\n".join(str(page(conn, cc, queued)) for cc in targets)
