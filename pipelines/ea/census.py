import json
import re
from datetime import date
from pathlib import Path

from ea import census_calendar, census_check
from ea.store import ROOT, connect

PAGES = ROOT / ".agents" / "spec" / "coverage"
CENSUS_FILES = Path(__file__).parent / "census"
RESEARCH = "## Research"
TICKET_REF = re.compile(r"class:([a-z]{2,3})/([a-z0-9_.-]+)")

CLASSES_SQL = """
select k.id, k.key, k.name_en, k.name, k.category, k.goal, k.valid_from, k.valid_to, k.first_held, k.earliest_record,
    k.contests_per_unit, k.finest_scheme_code, k.finest_note, k.disposition, k.disposition_reason, k.est_votes,
    k.effort, k.note, t.key as tier_key,
    (select sum(g.complete)::float / nullif(sum(g.total), 0) from coverage_goal g where g.class_id = k.id) as share,
    (select min(d.date) from census_date d where d.class_id = k.id and d.date >= %(today)s) as next_date
from census_class k
join census_tier t on t.id = k.tier_id
where k.polity_id = %(polity)s
order by t.key, k.key
"""


def polity_id(conn, cc: str) -> str:
    row = conn.execute("select id from polity where iso_code = %s", (cc.upper(),)).fetchone()
    if row is None:
        raise SystemExit(f"no polity {cc.upper()}")
    return row[0]


def open_classes(conn) -> list[dict]:
    found_held = census_check.held(conn)
    rows = conn.execute(
        """
        select k.id, lower(p.iso_code), k.key, coalesce(k.name_en, k.name), t.key, k.est_votes, k.effort
        from census_class k
        join census_tier t on t.id = k.tier_id
        join polity p on p.id = k.polity_id
        where k.disposition is null
        """
    ).fetchall()
    found = [
        {
            "polity": cc,
            "key": key,
            "name": name,
            "tier": tier,
            "est_votes": votes,
            "effort": effort,
            "score": (votes or 0) / (effort or 3),
        }
        for class_id, cc, key, name, tier, votes, effort in rows
        if not found_held.get(class_id)
    ]
    found.sort(key=lambda row: (-row["score"], row["polity"], row["key"]))
    return found


def status_of(row: dict, queued: set[tuple[str, str]], cc: str) -> str:
    if row["held"]:
        return "held"
    if row["disposition"]:
        return row["disposition"].replace("_", " ")
    return "queued" if (cc, row["key"]) in queued else "open"


def span(first, last) -> str:
    if first is None and last is None:
        return ""
    return f"{first.year if first else ''}-{last.year if last else ''}"


def cell(text) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ")


def table(head: list[str], rows: list[list]) -> list[str]:
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(cell(value) for value in row) + " |" for row in rows]
    return lines + [""]


def units(found: list[tuple]) -> str:
    if len(found) == 1 and found[0][0] is None:
        _, when, value, locator, publisher = found[0]
        return f"{value:,} on {when} ({publisher}, {locator})"
    parts = [
        f"{within or 'all'} {value:,} on {when} ({publisher})"
        for within, when, value, _, publisher in sorted(found, key=lambda row: row[0] or "")
    ]
    regions = f"{len(found)} region" + ("s" if len(found) > 1 else "")
    return f"{sum(row[2] for row in found):,} in {regions}: " + "; ".join(parts)


def render(conn, cc: str, queued: set[tuple[str, str]]) -> str:
    pid = polity_id(conn, cc)
    name = conn.execute(
        "select coalesce((select text from name where entity_id = %s and is_preferred limit 1), %s)", (pid, cc.upper())
    ).fetchone()[0]
    out = [
        f"# {name} election census",
        "",
        "Generated by `ea census " + cc.lower() + "` from the database; edit the research below the marker only.",
        "",
    ]

    tiers = conn.execute(
        """
        select t.id, t.key, coalesce(t.name_en, t.name), t.parent_tier_id, t.elects, t.valid_from, t.valid_to,
            t.polity_kind, t.scheme_code, w.iso_code, t.locator, s.publisher, s.url
        from census_tier t
        join source s on s.id = t.source_id
        left join polity w on w.id = t.within_polity_id
        where t.polity_id = %s
        """,
        (pid,),
    ).fetchall()
    counts: dict = {}
    for tier_id, when, value, locator, publisher, within in conn.execute(
        """
        select distinct on (c.tier_id, c.within_polity_id) c.tier_id, c.date, c.value, c.locator, s.publisher,
            w.iso_code
        from census_tier_count c
        join census_tier t on t.id = c.tier_id and t.polity_id = %s
        join source s on s.id = c.source_id
        left join polity w on w.id = c.within_polity_id
        order by c.tier_id, c.within_polity_id, c.date desc
        """,
        (pid,),
    ):
        counts.setdefault(tier_id, []).append((within, when, value, locator, publisher))
    keys = {tier[0]: tier[1] for tier in tiers}
    out += ["## Tiers", ""]
    rows = []
    for tier_id, key, label, parent, elects, vfrom, vto, kind, scheme, within, locator, publisher, _ in sorted(
        tiers, key=lambda t: t[1]
    ):
        count = counts.get(tier_id)
        rows.append(
            [
                key,
                label,
                keys.get(parent, ""),
                "yes" if elects else "no",
                kind or "",
                scheme or "",
                within or "",
                span(vfrom, vto),
                units(count) if count else "",
            ]
        )
    out += (
        table(["Key", "Tier", "Parent", "Elects", "Polity kind", "Scheme", "Within", "Years", "Units"], rows)
        if rows
        else ["None recorded.", ""]
    )

    found_held = census_check.held(conn)
    classes = [
        dict(zip([c.name for c in cur.description], record, strict=True))
        for cur in [conn.execute(CLASSES_SQL, {"polity": pid, "today": date.today()})]
        for record in cur.fetchall()
    ]
    for k in classes:
        k["held"] = found_held.get(k["id"], 0)
        k["next_date"] = k["next_date"] or census_calendar.class_next_date(conn, k["id"], date.today())
    cadence: dict = {}
    for (
        class_id,
        period,
        phase,
        month,
        day_rule,
        called,
        term,
        system,
        administered,
        statute,
        vfrom,
        vto,
    ) in conn.execute(
        """
        select c.class_id, c.period_years, c.phase, c.month, c.day_rule, c.called, c.term_years, (select n.text from name n where n.entity_id = c.electoral_system_id and n.is_preferred limit 1),
            c.administered_by, c.locator, c.valid_from, c.valid_to
        from election_cadence c
        where c.class_id in (select id from census_class where polity_id = %s)
        order by c.valid_from nulls first
        """,
        (pid,),
    ):
        text = f"every {period} y" if period else "irregular"
        text += f", month {month}" if month else ""
        text += f", {day_rule}" if day_rule else ""
        text += ", can be called early" if called else ""
        text += f", {system}" if system else ""
        text += f" ({statute}{', ' + span(vfrom, vto) if vfrom or vto else ''})"
        cadence.setdefault(class_id, []).append(text)
    access: dict = {}
    for class_id, role, platform, url, fmt, level, license_ in conn.execute(
        """
        select a.class_id, a.role, a.platform, a.url_pattern, a.format, a.access, a.license
        from results_access a
        where a.class_id in (select id from census_class where polity_id = %s)
        order by a.role, a.platform
        """,
        (pid,),
    ):
        access.setdefault(class_id, []).append(
            f"{role}: {platform} {url} ({fmt}, {level}{', ' + license_ if license_ else ''})"
        )

    tier_order = sorted({k["tier_key"] for k in classes})
    live = [k for k in classes if k["valid_to"] is None or k["valid_to"] >= date.today()]
    closed = [k for k in classes if k not in live]
    out += ["## Classes", ""]
    for tier in tier_order:
        out += [f"### {tier}", ""]
        rows = []
        for k in (k for k in live if k["tier_key"] == tier):
            share = k["share"]
            rows.append(
                [
                    k["key"],
                    k["name_en"] or k["name"],
                    k["category"],
                    span(k["valid_from"], k["valid_to"]),
                    "; ".join(cadence.get(k["id"], [])),
                    "; ".join(access.get(k["id"], [])),
                    (k["finest_scheme_code"] or "") + (f" ({k['finest_note']})" if k["finest_note"] else ""),
                    status_of(k, queued, cc.lower()) + (f": {k['disposition_reason']}" if k["disposition"] else ""),
                    f"{share:.0%}" if share is not None else "0%" if not k["disposition"] else "",
                    k["next_date"] or "",
                ]
            )
        out += table(
            [
                "Class",
                "Name",
                "Category",
                "Years",
                "Cadence",
                "Publishers",
                "Finest unit",
                "Status",
                "Coverage",
                "Next",
            ],
            rows,
        )
    if not classes:
        out += ["None recorded.", ""]
    if closed:
        out += ["## Abolished classes", ""]
        out += table(
            ["Class", "Name", "Years", "Status"],
            [
                [
                    k["key"],
                    k["name_en"] or k["name"],
                    span(k["valid_from"], k["valid_to"]),
                    status_of(k, queued, cc.lower()),
                ]
                for k in closed
            ],
        )
    ranked = sorted(
        (k for k in live if status_of(k, queued, cc.lower()) in ("open", "queued")),
        key=lambda k: -((k["est_votes"] or 0) / (k["effort"] or 3)),
    )
    out += ["## Open classes", ""]
    out += (
        table(
            ["Class", "Status", "Est. votes", "Effort"],
            [
                [
                    k["key"],
                    status_of(k, queued, cc.lower()),
                    f"{k['est_votes']:,}" if k["est_votes"] else "",
                    k["effort"] or "",
                ]
                for k in ranked
            ],
        )
        if ranked
        else ["None.", ""]
    )
    return "\n".join(out)


def page(conn, cc: str, queued: set[tuple[str, str]] | None = None) -> Path:
    return keep_research(PAGES / f"{cc.lower()}-census.md", render(conn, cc, queued or set()))


WORLD_SQL = """
select w.iso_code, w.name_en, w.status::text, w.within_iso, w.reason, w.electorate, w.electorate_date, w.locator,
    s.publisher, s.title, w.recognized_within
from census_world w
join source s on s.id = w.source_id
order by w.iso_code
"""

HELD_SQL = """
select case when p.kind = 'de_facto_state' then p.iso_code else split_part(p.iso_code, '-', 1) end,
    count(distinct e.id), min(extract(year from e.date_from))::int,
    max(extract(year from e.date_from))::int
from election e
join polity p on p.id = e.polity_id
where p.iso_code is not null and e.status <> 'scheduled' and e.date_from <= current_date
group by 1
"""

PUBLISHED_SQL = "select distinct p.iso_code from census_class k join polity p on p.id = k.polity_id"


def census_state(iso: str, published: set[str]) -> str:
    if iso in published:
        return "published"
    return "in progress" if (CENSUS_FILES / f"{iso.lower()}.json").exists() else "none"


def render_world(conn) -> str:
    if conn.execute("select to_regclass('public.census_world')").fetchone() == (None,):
        raise SystemExit("census_world is not in this database yet")
    rows = conn.execute(WORLD_SQL).fetchall()
    held = {iso: (count, first, last) for iso, count, first, last in conn.execute(HELD_SQL)}
    published = {iso for (iso,) in conn.execute(PUBLISHED_SQL)}
    statuses = {
        status: sum(row[2] == status for row in rows) for status in ("own", "within", "none", "de_facto", "former")
    }
    own = [row for row in rows if row[2] == "own"]
    states = {row[0]: census_state(row[0], published) for row in own}
    tally = {state: sum(value == state for value in states.values()) for state in ("published", "in progress", "none")}
    out = [
        "# World election census",
        "",
        (
            "Generated by `ea census world` from the database; edit `pipelines/ea/census/world.json` and the research below"
            " the marker only."
        ),
        "",
        (
            f"{len(rows)} rows, one per ISO 3166-1 code, Kosovo, and each de facto or former state: {statuses['own']}"
            f" hold elections of their own, {statuses['within']} hold them within another polity, {statuses['none']}"
            f" hold none, {statuses['de_facto']} are de facto states recognized within another polity, and"
            f" {statuses['former']} are former states. Of the"
            f" {statuses['own']} with elections of their own, {tally['published']} have a published census,"
            f" {tally['in progress']} have one in progress, and {tally['none']} have none yet."
        ),
        "",
        "## Own",
        "",
    ]

    def elections(iso: str) -> str:
        count, first, last = held.get(iso, (0, None, None))
        return f"{count:,} ({first}-{last})" if count else "0"

    def cite(publisher: str, title: str, locator: str) -> str:
        return f"{publisher}, {title}, <{locator}>"

    out += table(
        ["Code", "Country", "Census", "Held elections", "Electorate", "Cite"],
        [
            [
                iso,
                name,
                states[iso],
                elections(iso),
                f"{electorate:,} ({when})" if electorate is not None else "",
                cite(publisher, title, locator),
            ]
            for iso, name, _, _, _, electorate, when, locator, publisher, title, _ in own
        ],
    )
    out += ["## Within another polity", ""]
    out += table(
        ["Code", "Country", "Within", "Held elections", "Reason", "Cite"],
        [
            [iso, name, within, elections(iso), reason, cite(publisher, title, locator)]
            for iso, name, status, within, reason, _, _, locator, publisher, title, _ in rows
            if status == "within"
        ],
    )
    out += ["## De facto states", ""]
    out += table(
        ["Code", "Country", "Recognized within", "Held elections", "Reason", "Cite"],
        [
            [iso, name, recognized, elections(iso), reason, cite(publisher, title, locator)]
            for iso, name, status, _, reason, _, _, locator, publisher, title, recognized in rows
            if status == "de_facto"
        ],
    )
    out += ["## Former states", ""]
    out += table(
        ["Code", "Country", "Held elections", "Reason", "Cite"],
        [
            [iso, name, elections(iso), reason, cite(publisher, title, locator)]
            for iso, name, status, _, reason, _, _, locator, publisher, title, _ in rows
            if status == "former"
        ],
    )
    out += ["## No elections", ""]
    out += table(
        ["Code", "Country", "Reason", "Cite"],
        [
            [iso, name, reason, cite(publisher, title, locator)]
            for iso, name, status, _, reason, _, _, locator, publisher, title, _ in rows
            if status == "none"
        ],
    )
    return "\n".join(out)


def keep_research(path: Path, body: str) -> Path:
    kept = ""
    if path.exists():
        text = path.read_text()
        at = text.find("\n" + RESEARCH)
        if at >= 0:
            kept = text[at + 1 :]
        elif text.startswith(RESEARCH):
            kept = text
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body.rstrip("\n") + "\n\n" + (kept.rstrip("\n") if kept else RESEARCH + "\n\n") + "\n")
    return path


def world_page(conn) -> Path:
    return keep_research(PAGES / "world-census.md", render_world(conn))


def queued_classes(text: str) -> set[tuple[str, str]]:
    return set(TICKET_REF.findall(text))


def mark(conn, queued: set[tuple[str, str]]) -> str:
    open_keys = {(r["polity"], r["key"]) for r in open_classes(conn)}
    wanted: dict[str, list[dict[str, str]]] = {}
    for polity, key in sorted(queued & open_keys):
        wanted.setdefault(polity, []).append({"key": key, "status": "queued"})
    conn.execute(
        "update coverage_polity set classes = '[]' where classes <> '[]'::jsonb and not (polity = any(%s))",
        (list(wanted),),
    )
    for polity, entries in wanted.items():
        conn.execute("update coverage_polity set classes = %s where polity = %s", (json.dumps(entries), polity))
    conn.commit()
    return f"marked {sum(len(v) for v in wanted.values())} queued classes in {len(wanted)} polities"


def run(targets: list[str], as_json: bool, queued_file: str | None) -> str:
    with connect() as conn:
        if targets == ["open"]:
            found = open_classes(conn)
            if as_json:
                return json.dumps(found, indent=2)
            return "\n".join(f"{r['polity']}/{r['key']}\t{r['score']:.0f}\t{r['name']}" for r in found)
        queued = queued_classes(Path(queued_file).read_text()) if queued_file else set()
        if targets == ["mark"]:
            return mark(conn, queued)
        if targets == ["world"]:
            return str(world_page(conn))
        return "\n".join(str(page(conn, cc, queued)) for cc in targets)
