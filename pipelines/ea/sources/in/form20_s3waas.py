def _lines(page: pymupdf.Page) -> list[tuple[float, list[tuple[float, float, float, str]]]]:
    """The page's words grouped into lines by their vertical centers: (y, [(x0, x1, y, text)])."""
    rows: dict[float, list[tuple[float, float, float, str]]] = {}
    for x0, y0, x1, y1, text, *_ in page.get_text("words"):
        center = (y0 + y1) / 2
        line = next((k for k in rows if abs(k - center) < 2.5), center)
        rows.setdefault(line, []).append((x0, x1, center, text))
    return [(y, sorted(words)) for y, words in sorted(rows.items())]


SEGMENT = re.compile(r"(?:segment|Segment|SEGMENT|Constituency|constituency)\W*?(\d{1,3})\s*[-–.]\s*([A-Za-z]{3,})")


def _segment(text: str) -> int | None:
    for match in SEGMENT.finditer(text):
        number = int(match.group(1))
        if number in PC_OF:
            return number
    return None


LABEL = re.compile(r"(?:AC-)?(\d{1,3})\s*[-–.]?\s*[A-Za-z]")


@functools.cache
def labels() -> dict[str, int]:
    """The segment each sheet's link names in the table row that holds it on the district page (the last number
    followed by a name in the row), for sheets whose header names the segment in a font with no Unicode text."""
    out: dict[str, int] = {}
    for page, url in links():
        artifact = _cached(page)
        if artifact is None:
            continue
        text = artifact.path.read_text(encoding="utf-8", errors="replace")
        at = text.find(url.split("id=")[-1] if "drive.google.com" in url else url)
        start, end = text.rfind("<tr", 0, at), text.find("</tr>", at)
        if start < 0 or end < 0 or at - start > 3000:
            continue
        row = " ".join(unescape(re.sub(r"<[^>]+>", " ", text[start:end])).split())
        row = re.sub(r"\d+(\.\d+)?\s*[KkMm][Bb]\b", " ", row)  # file sizes
        found = [int(m.group(1)) for m in LABEL.finditer(row) if int(m.group(1)) in PC_OF]
        if found:
            out[url] = found[-1]
    return out


def read(url: str) -> Sheet | str:
    """Read one sheet, or say why it is left out."""
    artifact = _cached(url)
    if artifact is None:
        return "not fetched"
    doc = pymupdf.open(artifact.path)
    first = doc[0].get_text() if len(doc) else ""
    if len(first.strip()) < 50:
        return "scanned, with no text layer"
    ac = _segment(first.replace("\n", " ")) or labels().get(url)
    lines: list[tuple[int, float, list[tuple[float, float, float, str]]]] = []
    for number in range(len(doc)):
        page = doc[number]
        lines += [(number, y, words) for y, words in _lines(page)]
    data: list[tuple[int, float, list[tuple[str, float]]]] = []
    for number, y, words in lines:
        tokens = [w[3] for w in words]
        if not tokens or not CODE.match(tokens[0]):
            continue
        values = [
            (w[3], (w[0] + w[1]) / 2) for i, w in enumerate(words) if INT.match(w[3]) or (i < 2 and CODE.match(w[3]))
        ]
        if len(values) < 7:
            continue
        ints = [int(v) for v, _ in values if v.isdigit()]
        if ints == list(range(1, len(ints) + 1)):
            continue  # the row that numbers the columns
        data.append((number, y, values))
    if not data:
        return "no table rows in the text layer"
    width = Counter(len(v) for _, _, v in data).most_common(1)[0][0]
    rows = [r for r in data if len(r[2]) == width]
    layout = _layout([[v for v, _ in r[2]] for r in rows])
    if layout is None:
        return f"columns do not reconcile ({width} numbers a row)"
    lead, k, tendered = layout
    rows += _short_rows([r for r in data if width - 3 <= len(r[2]) < width], rows, lead, k)
    rows.sort(key=lambda r: (r[0], r[1]))
    parsed: list[Row] = []
    for _, _, values in rows:
        v = [x for x, _ in values]
        n = [int(x) if x.isdigit() else 0 for x in v]
        tail = n[lead + k :]
        parsed.append(
            Row(
                serial=int(re.sub(r"\D", "", v[0])),
                station=v[1] if lead == 2 else v[0],
                votes=n[lead : lead + k],
                valid=tail[0],
                rejected=tail[1],
                nota=tail[2],
                total=tail[3],
                tendered=tail[4] if tendered else None,
            )
        )
    if ac is None:
        return "no segment number in the header"
    sums = [sum(r.votes[i] for r in parsed) for i in range(k)] + [
        sum(r.valid for r in parsed),
        sum(r.rejected for r in parsed),
        sum(r.nota for r in parsed),
        sum(r.total for r in parsed),
    ]
    checked = False
    for _, _, words in lines:
        ints = [int(w[3]) for w in words if INT.match(w[3])]
        if len(ints) >= k + 4 and ints[: k + 4] == sums:
            checked = True
            break
    names = _names(doc, rows[0], lead, k)
    sheet = Sheet(url, artifact.sha256, ac, names, parsed, len(doc), checked)
    bad = [r.serial for r in parsed if sum(r.votes) != r.valid or r.valid + r.rejected + r.nota != r.total]
    if bad:
        sheet.problems.append(f"rows that do not add up: {bad[:10]}")
    return sheet


def _short_rows(
    short: list[tuple[int, float, list[tuple[str, float]]]],
    full: list[tuple[int, float, list[tuple[str, float]]]],
    lead: int,
    k: int,
) -> list[tuple[int, float, list[tuple[str, float]]]]:
    """Rows with blank cells: each figure goes to the column whose figures sit nearest, and a blank cell counts as
    zero only when the row then reconciles."""
    width = len(full[0][2])
    centers = [sorted(r[2][i][1] for r in full)[len(full) // 2] for i in range(width)]
    out = []
    for page, y, values in short:
        cells: list[tuple[str, float] | None] = [None] * width
        for value, x in values:
            i = min(range(width), key=lambda j: abs(centers[j] - x))
            if cells[i] is not None:
                break
            cells[i] = (value, x)
        else:
            if any(cells[i] is None for i in range(lead)):
                continue
            filled = [c if c is not None else ("0", centers[i]) for i, c in enumerate(cells)]
            n = [int(v) if v.isdigit() else 0 for v, _ in filled]
            tail = n[lead + k :]
            if sum(n[lead : lead + k]) == tail[0] and tail[0] + tail[1] + tail[2] == tail[3]:
                out.append((page, y, filled))
    return out


def _layout(rows: list[list[str]]) -> tuple[int, int, bool] | None:
    """The number of leading columns (serial, or serial and station number), of candidates, and whether the tendered
    votes close the row, chosen as the reading under which the most rows reconcile."""
    width = len(rows[0])
    best: tuple[int, tuple[int, int, bool]] | None = None
    for lead in (1, 2):
        for tendered in (True, False):
            k = width - lead - (5 if tendered else 4)
            if k < 2:
                continue
            good = 0
            for v in rows:
                n = [int(x) if x.isdigit() else 0 for x in v]
                c, tail = n[lead : lead + k], n[lead + k :]
                if sum(c) == tail[0] and tail[0] + tail[1] + tail[2] == tail[3]:
                    good += 1
            if best is None or good > best[0]:
                best = (good, (lead, k, tendered))
    if best is None or best[0] < max(3, 0.9 * len(rows)):
        return None
    return best[1]


def _names(doc: pymupdf.Document, first: tuple[int, float, list[tuple[str, float]]], lead: int, k: int) -> list[str]:
    """The candidates' names from the header above the first row, each word put in the column whose figures sit
    nearest below it."""
    page_number, top, values = first
    xs = [x for _, x in values[lead : lead + k]]
    gap = min((b - a for a, b in pairwise(xs)), default=40)
    words: list[list[tuple[float, float, str]]] = [[] for _ in range(k)]
    started = False
    for y, line in _lines(doc[page_number]):
        if y >= top - 1:
            break
        text = " ".join(w[3] for w in line).upper()
        if "FAVOUR" in text:
            started = True
            continue
        if not started:
            continue
        for x0, x1, center, word in line:
            if INT.match(word) or word.upper().strip(".") in HEADING:
                continue
            mid = (x0 + x1) / 2
            i = min(range(k), key=lambda j: abs(xs[j] - mid))
            if abs(xs[i] - mid) <= gap * 0.75:
                words[i].append((center, x0, word))
    return [" ".join(w for _, _, w in sorted(column)) for column in words]


# The Commission's result pages.


@dataclass
class Candidate:
    name: str
    party: str
    votes: int
    won: bool
    option: str | None = None  # the option in.eci_results holds for this candidate
    party_id: str | None = None  # the party in.eci_results holds


def _built(key: str) -> pathlib.Path:
    path = package.folder(key) / "build"
    if not (path / "package.json").exists():
        raise LookupError(f"{key} is not built here; build it (uv run ea parse in.eci_results) before this pipeline")
    return path


@functools.cache
def held() -> dict[int, list[Candidate]]:
    """The candidates of each Uttar Pradesh constituency that in.eci_results holds, with its option ids, in its ballot
    order, NOTA included; the votes are the declared totals (EVM and postal) it stores."""
    build, registry = _built(RESULTS_PACKAGE), _built(f"{RESULTS}/registry")
    options = pl.read_parquet(build / "contest_option.parquet")
    votes = (
        pl.read_parquet(build / "result_value.parquet")
        .filter(pl.col("measure") == VOTES, pl.col("option_id").is_not_null())
        .group_by("option_id")
        .agg(pl.col("value").sum())
    )
    won = set(pl.read_parquet(build / "outcome.parquet").filter(pl.col("kind") == "elected")["option_id"])
    names = pl.read_parquet(registry / "name.parquet").filter(pl.col("kind") == "official")
    party_names = dict(zip(names["entity_id"], names["text"], strict=True))
    total = dict(zip(votes["option_id"], votes["value"], strict=True))
    out: dict[int, list[Candidate]] = {}
    for pc in PCS:
        rows = options.filter(pl.col("contest_id") == held_contest(pc)).sort("ballot_position", nulls_last=True)
        listed = []
        for row in rows.iter_rows(named=True):
            nota = row["kind"] == "none_of_the_above"
            party = "None of the Above" if nota else party_names[row["party_id"]] if row["party_id"] else "Independent"
            listed.append(
                Candidate(row["ballot_label"], party, total[row["id"]], row["id"] in won, row["id"], row["party_id"])
            )
        if listed:
            out[pc] = listed
    return out


@functools.cache
def held_parties() -> dict[str, str]:
    """The parties in.eci_results holds, by name."""
    registry = _built(f"{RESULTS}/registry")
    ids = set(pl.read_parquet(registry / "party.parquet")["id"])
    names = pl.read_parquet(registry / "name.parquet").filter(pl.col("kind") == "official")
    return {text: id for id, text in zip(names["entity_id"], names["text"], strict=True) if id in ids}


def eci_artifact(pc: int) -> raw.Artifact | None:
    target = ECI_PAGE.format(pc)
    index = json.loads((DATA / "raw" / SOURCE / "index.json").read_text())
    for url in index:
        if url == target or url.endswith("/" + target):
            return raw.cached(SOURCE, url)
    return None


@functools.cache
def eci(pc: int) -> list[Candidate] | None:
    """The candidates the Commission lists for a constituency, with NOTA last under the party "None of the Above"."""
    artifact = eci_artifact(pc)
    if artifact is None:
        return None
    text = artifact.path.read_text(encoding="utf-8", errors="replace")
    out: list[Candidate] = []
    for box in text.split("class='cand-box'")[1:]:
        status = re.search(r"class='status (\w+)'", box)
        votes = re.search(r"<div>\s*(\d+)\s*<span>", box)
        name = re.search(r"<h5>(.*?)</h5>", box, re.DOTALL)
        party = re.search(r"<h6>(.*?)</h6>", box, re.DOTALL)
        if not (votes and name and party):
            continue
        out.append(
            Candidate(
                " ".join(unescape(name.group(1)).split()),
                " ".join(unescape(party.group(1)).split()),
                int(votes.group(1)),
                bool(status and status.group(1) == "won"),
            )
        )
    return out or None


def _fold(name: str) -> str:
    return re.sub(r"[^A-Z ]+", " ", name.upper()).strip()


def _similar(a: str, b: str) -> float:
    a, b = _fold(a), _fold(b)
    if not a or not b:
        return 0.0
    ta, tb = set(a.split()), set(b.split())
    overlap = len(ta & tb) / max(len(ta | tb), 1)
    return max(overlap, SequenceMatcher(None, a.replace(" ", ""), b.replace(" ", "")).ratio())


def match(names: list[str], candidates: list[Candidate]) -> list[int] | None:
    """Pair each column's name with one of the Commission's candidates (NOTA aside), best pairs first; None unless
    every column finds a distinct candidate with a close name."""
    pool = [i for i, c in enumerate(candidates) if c.party != "None of the Above"]
    if len(names) != len(pool):
        return None
    pairs = sorted(((_similar(n, candidates[i].name), j, i) for j, n in enumerate(names) for i in pool), reverse=True)
    chosen: dict[int, int] = {}
    used: set[int] = set()
    for score, j, i in pairs:
        if j in chosen or i in used:
            continue
        chosen[j] = i
        used.add(i)
    if len(chosen) != len(names):
        return None
    if min(_similar(names[j], candidates[i].name) for j, i in chosen.items()) < 0.5:
        return None
    return [chosen[j] for j in range(len(names))]


# Putting a constituency together.


@dataclass
class Constituency:
    number: int
    candidates: list[Candidate] | None  # the Commission's list, or None where no capture of its page was reached
    sheets: list[Sheet]
    columns: list[int | None]  # for each Form 20 column, the index of its candidate in `candidates`
    names: list[str]  # each column's name as the sheets print it
    left_out: list[str]


def _column_names(sheets: list[Sheet], k: int) -> list[str]:
    """Each column's name: the longest reading among the constituency's sheets."""
    out = []
    for j in range(k):
        readings = Counter(s.names[j] for s in sheets if s.names[j])
        out.append(max(readings, key=lambda n: (readings[n], len(n))) if readings else "")
    return out


def _assign(sheets: list[Sheet], candidates: list[Candidate]) -> list[int] | None:
    """Pair each column with a candidate by name, best pairs first, then check the pairing against the declared
    totals: no column's EVM votes may exceed its candidate's declared total, and where every segment is read, the
    difference (the postal votes) must be small."""
    k = len(sheets[0].names)
    pool = [i for i, c in enumerate(candidates) if c.party != "None of the Above"]
    if len(pool) != k:
        return None
    score = {(j, i): max(_similar(s.names[j], candidates[i].name) for s in sheets) for j in range(k) for i in pool}
    chosen: dict[int, int] = {}
    used: set[int] = set()
    for (j, i), _ in sorted(score.items(), key=lambda item: -item[1]):
        if j not in chosen and i not in used:
            chosen[j], used = i, used | {i}
    weak = [j for j in chosen if score[(j, chosen[j])] < 0.6]
    if len(weak) > 2:
        return None
    sums = [sum(r.votes[j] for s in sheets for r in s.rows) for j in range(k)]
    if any(sums[j] > candidates[i].votes for j, i in chosen.items()):
        return None
    return [chosen[j] for j in range(k)]


@functools.cache
def constituencies() -> dict[int, Constituency]:
    sheets: dict[int, list[Sheet]] = {}
    out: dict[int, Constituency] = {}
    skipped: dict[int, list[str]] = {}
    seen: set[str] = set()
    for _, url in links():
        sheet = read(url)
        if isinstance(sheet, str):
            continue
        if sheet.sha256 in seen or any(s.ac == sheet.ac for s in sheets.get(PC_OF[sheet.ac], [])):
            continue
        if not sheet.checked or sheet.problems:
            skipped.setdefault(PC_OF[sheet.ac], []).append(
                f"segment {sheet.ac}: {'; '.join(sheet.problems) or 'no printed totals line matches its rows'}"
            )
            continue
        seen.add(sheet.sha256)
        sheets.setdefault(PC_OF[sheet.ac], []).append(sheet)
    for pc in PCS:
        candidates = held().get(pc) or eci(pc)
        found = sorted(sheets.get(pc, []), key=lambda s: s.ac)
        left = list(skipped.get(pc, []))
        widths = Counter(len(s.names) for s in found)
        if widths:
            k = widths.most_common(1)[0][0]
            for s in found:
                if len(s.names) != k:
                    left.append(f"segment {s.ac}: {len(s.names)} candidate columns, not {k}")
            found = [s for s in found if len(s.names) == k]
        columns: list[int | None] = []
        if found and candidates:
            assigned = _assign(found, candidates)
            if assigned is None:
                left += [
                    f"segment {s.ac}: its columns could not be matched to the Commission's candidates" for s in found
                ]
                found = []
            else:
                columns = list(assigned)
        elif found:
            if any(not n for n in _column_names(found, len(found[0].names))):
                left += [f"segment {s.ac}: a column's name could not be read" for s in found]
                found = []
            else:
                columns = [None] * len(found[0].names)
        if not found and not candidates:
            continue
        names = _column_names(found, len(found[0].names)) if found else []
        out[pc] = Constituency(pc, candidates, found, columns, names, left)
    return out


def manifest() -> dict[str, object]:
    """Each segment of the state: the sheet read for it, or why none was."""
    read_by_ac = {s.ac: s.url for c in constituencies().values() for s in c.sheets}
    linked: dict[int, list[tuple[str, str]]] = {}
    unread: list[dict[str, str]] = []
    for page, url in links():
        sheet = read(url)
        if isinstance(sheet, str):
            unread.append({"page": page, "url": url, "why": sheet})
        else:
            linked.setdefault(sheet.ac, []).append((page, url))
    return {
        "segments": len(PC_OF),
        "read": len(read_by_ac),
        "sheets": {str(ac): url for ac, url in sorted(read_by_ac.items())},
        "linked_unread": {str(ac): [u for _, u in urls] for ac, urls in sorted(linked.items()) if ac not in read_by_ac},
        "unreadable": unread,
        "left_out": {str(pc): c.left_out for pc, c in sorted(constituencies().items()) if c.left_out},
    }


