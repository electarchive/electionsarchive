def person_name(text: str) -> str:
    """Sentence-case an upper-case name, keeping initials and dotted abbreviations."""
    words = []
    for word in text.split():
        words.append(word.capitalize() if word.isupper() and "." not in word and len(word) > 1 else word)
    return " ".join(words)


