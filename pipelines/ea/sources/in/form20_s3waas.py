def _own_contest(p: Package, c: Constituency) -> tuple[str, dict[str, str], str]:
    name, _, _ = PCS[c.number]
    area = pc_area(c.number)
    p.external.add(area)
    contest = key("contest", 2024, ECI_STATE, c.number)
    p.add(
        "contest",
        id=contest,
        election_id=ELECTION,
        kind="body_seats",
        body_id=BODY,
        district_area_id=area,
        magnitude=1,
        round_number=1,
        electoral_system_id=FPTP,
        default_result_kind="counted",
    )
    p.name(contest, f"{name}, {STATE}", "en", "official")
    p.add(
        "slug", path=f"{ELECTION_PATH}/{ECI_STATE.lower()}-{c.number}-{slug(name)}", entity_id=contest, is_current=True
    )
    # The options: the Commission's candidates and NOTA, or, without its page, the names the sheets print.
    options: dict[str, str] = {}  # by the candidate's index
    position = {}
    if c.candidates:
        for j, i in enumerate(c.columns):
            if i is not None:
                position[i] = j + 1
        listed = list(enumerate(c.candidates))
    else:
        listed = [(j, Candidate(n, "", 0, False)) for j, n in enumerate(c.names)]
        position = {j: j + 1 for j in range(len(c.names))}
    nota = key("option", 2024, ECI_STATE, c.number, "NOTA")
    for i, x in listed:
        if x.party == "None of the Above":
            continue
        option = key("option", 2024, ECI_STATE, c.number, _fold(x.name))
        if option in options.values():
            option = key("option", 2024, ECI_STATE, c.number, _fold(x.name), i)
        options[str(i)] = option
        person = key("person", 2024, ECI_STATE, c.number, _fold(x.name), i)
        label = person_name(x.name)
        p.add("person", id=person)
        p.name(person, label, "en", "official")
        coded = x.party not in ("", "Independent")
        if coded and x.party in held_parties():
            p.external.add(party(x.party))
        p.add(
            "contest_option",
            id=option,
            contest_id=contest,
            kind="candidate",
            party_id=party(x.party) if coded else None,
            ballot_position=position.get(i),
            ballot_label=label,
        )
        p.add(
            "candidacy",
            id=key("candidacy", 2024, ECI_STATE, c.number, i),
            person_id=person,
            option_id=option,
            role="head",
            ballot_name=label,
            member_of_party_id=party(x.party) if coded else None,
            is_independent=True if x.party == "Independent" else None,
        )
    p.add(
        "contest_option",
        id=nota,
        contest_id=contest,
        kind="none_of_the_above",
        ballot_position=len(listed) + (0 if c.candidates else 1),
        ballot_label="NOTA",
    )
    if c.candidates:
        rs = key("result_set", 2024, ECI_STATE, c.number, "eci")
        p.add(
            "result_set",
            id=rs,
            election_id=ELECTION,
            contest_id=contest,
            stage="official",
            kind="counted",
            source_id=ECI_SOURCE,
            status="active",
            is_default=True,
            completeness=1.0,
        )
        p.add(
            "note",
            id=key("note", rs),
            entity_id=rs,
            kind="methodology",
            body_md="Each candidate's total votes (EVM and postal) and NOTA's, and the result, as the Election "
            "Commission's candidate-wise result page for the constituency shows them, read from an archived capture.",
            lang="en",
        )
        unit = key("unit", 2024, ECI_STATE, c.number)
        p.add(
            "reporting_unit",
            id=unit,
            polity_id=INDIA,
            scheme_code="in.pc",
            code=f"2024:{ECI_STATE}:{c.number}",
            area_relation="equals",
            area_id=area,
            kind="standard",
        )
        for i, x in enumerate(c.candidates):
            option = nota if x.party == "None of the Above" else options[str(i)]
            _value(p, rs, unit, option, VOTES, x.votes)
            if x.party != "None of the Above":
                p.add(
                    "outcome",
                    result_set_id=rs,
                    option_id=option,
                    kind="elected" if x.won else "lost",
                    seats=int(x.won),
                )
    return contest, options, nota


