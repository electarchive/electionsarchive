"""India's 2024 Lok Sabha general election by polling station, from the Form 20 sheets district administrations post.

After a count, each Assistant Returning Officer signs Form 20 (Part I) for one assembly segment of a parliamentary
constituency: one row per polling station with the EVM votes for each candidate, the total of valid votes, the rejected
votes, the votes for "None of the Above" (NOTA), the total, and the tendered votes. The Chief Electoral Officer's site
refuses requests from outside India, but most of Uttar Pradesh's 75 district administrations post the sheets of their
segments on their NIC portals (`<district>.nic.in`, built on S3WaaS), with the files on `cdn.s3waas.gov.in`. The
district's own site search for "form 20" leads to the page that links them; this module reads those pages, follows
their links, and identifies each sheet by the segment it prints, not by the link's label.

Form 20 Part I carries the EVM votes only. The postal ballots are counted for the whole parliamentary constituency
(Part II), which the districts do not post, so a constituency's sum here falls short of its declared total by its postal
votes. Form 20 also prints candidates by name only. Their parties, the declared totals, and who was elected come from
the Commission's result pages (`results.eci.gov.in/PcResultGenJune2024/candidateswise-S24<n>.htm`), read from archived
captures.

The election, the Lok Sabha, and 73 of the state's 80 constituency contests, with their candidates and declared totals,
are already held by in.eci_results; each Form 20 result set attaches to that contest and its options and stays beside
its default declared count, and the module reads the contests from that pipeline's built package. For constituencies
in.eci_results leaves out, this pipeline writes the contest itself, with the declared totals of an archived capture
as its default where one was reached.

Many sheets are computer-generated by the Commission's counting software ("Encore") with a text layer; others are typed
in a legacy Hindi font or scanned. A sheet is read only when its rows reconcile: candidate votes add to the valid votes,
valid, rejected, and NOTA votes add to the total, and the station rows add to the sheet's printed totals. Its columns
are named from its header (or from a sibling segment of the same constituency with the same ballot) and matched to the
Commission's candidate list. A sheet that does not meet all of that is left out and listed in the coverage manifest.
"""

